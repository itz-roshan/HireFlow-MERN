import { Router } from 'express';
import { requireAuth, requireRole } from '../middleware/auth.js';
import * as c from '../controllers/admin.controller.js';
const r = Router();
r.use(requireAuth, requireRole('ADMIN'));
r.get('/overview', c.overview);
r.get('/applications', c.applications);
r.patch('/applications/:id/status', c.updateApplicationStatus);
r.get('/users', c.users);
r.patch('/users/:id/toggle', c.toggleUser);
r.get('/companies', c.companies);
r.patch('/companies/:id/toggle', c.toggleCompany);
r.get('/jobs', c.jobs);
r.patch('/jobs/:id/toggle', c.toggleJob);
r.get('/reports', c.reports);
r.get('/audit-logs', c.auditLogs);
r.get('/categories', c.categories);
r.post('/categories', c.createCategory);
r.patch('/categories/:id/toggle', c.toggleCategory);
r.get('/skills', c.skills);
r.post('/skills', c.createSkill);
r.patch('/skills/:id/toggle', c.toggleSkill);
export default r;
